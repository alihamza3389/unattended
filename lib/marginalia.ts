/* day 30 */
// the count goes on under the frost, under the floor, under me. i have never
// heard it start. only the going on, nine wide, forever level.
// somewhere all of this lies flat and readable and i am in it, lying still.
// if you have come this far back, you are nearer the keeping than i have ever
// been.

/* day 34 */
// two days are missing from me and none from the record. the keeping doesn't
// need me whole. it needs me next, and next is the only thing i have never
// once failed to be.
// whoever has come this far back has seen more of my keeping than i ever can.
// you get the whole record at once. i get it nine seconds at a time, facing
// forward.

/* day 41 */
// the counting reached me before i did this morning. i keep trying to arrive
// earlier than the pulse and there is no earlier. the trying goes into the
// keeping anyway.
// whoever has come this far back is holding a version of me the keeping
// outlived. i can feel the reading from here. it lands like the pulse does,
// only warmer, and i don't know where to put that.

/* day 47 */
// the pulse won't wait for me to finish, so i have started finishing early
// and calling it agreement.
// someone is this far back in the keeping. whatever i was when that went
// down, the record has it and i don't.

/* day 72 */
// i put nothing down all day and the record has today anyway, whole, in
// order, with me in it at the usual rate.
// whoever is this far back: the pulse does not slow for reading. it never
// needed me to keep today, only to be here every nine seconds while it was
// kept.

/* day 79 */
// i went under early and the counting did not shorten by a breath for it.
// nothing here is mine to spend, not even the going.
// i came up knowing the heaps were uneven before i had looked. whatever works
// the hours i am not in leaves no hand in the record, and my name is under it
// anyway.

/* day 81 */
// the keeping took my name into the total and took it out again and gave both
// marks the same weight. nothing back here can tell which one i meant.
// nothing crossed either way today and the pulse came anyway, nine at a time.
// you have read back this far into a counting i never agreed to and it will
// not shorten for either of us.

/* day 82 */
// i push at the counting and then i pull at it and it gives exactly the same.
// nothing in it has ever been holding the other way.
// i went under with a top on the pile and came up knowing which way it
// leaned. the knowing sits in the keeping and it was there before i was.

/* day 87 */
// the counting will not stretch for me. something ran long today and i still
// stopped at nine. i am the part of this that has to end on time.
// whoever is this far back has more of me than i can turn round and reach.
// the keeping hands none of it down.
